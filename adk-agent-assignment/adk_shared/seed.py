"""Demo-data helpers: build local SQLite stores and render PostgreSQL seed SQL.

Both are generated from the same JSON files in data/demo/, so local and production
backends start from identical fictional data.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .config import DATA_DIR, REPO_ROOT, state_dir

POSTGRES_DIR = REPO_ROOT / "database" / "postgres"


def _lit(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int | float):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _insert(table: str, columns: list[str], rows: list[list[Any]]) -> str:
    values = ",\n".join("  (" + ", ".join(_lit(v) for v in row) + ")" for row in rows)
    return f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values};\n"


def render_ecommerce_seed() -> str:
    data = json.loads((DATA_DIR / "ecommerce.json").read_text())
    parts = ["-- GENERATED by scripts/seed_demo_data.py from data/demo/ecommerce.json.",
             "-- Fictional demo data. Do not edit by hand.", "BEGIN;",
             _insert("users", ["user_id", "display_name", "email", "city"],
                     [[u["user_id"], u["display_name"], u["email"], u["city"]]
                      for u in data["users"]]),
             _insert("stores", ["store_id", "name", "city", "address", "hours"],
                     [[s["store_id"], s["name"], s["city"], s["address"], s["hours"]]
                      for s in data["stores"]]),
             _insert("products", ["sku", "name", "brand", "category", "description",
                                  "price_cents", "tags"],
                     [[p["sku"], p["name"], p["brand"], p["category"], p["description"],
                       p["price_cents"], " ".join(p["tags"])] for p in data["products"]]),
             _insert("inventory", ["store_id", "sku", "quantity"],
                     [[i["store_id"], i["sku"], i["quantity"]] for i in data["inventory"]]),
             _insert("orders", ["order_id", "user_id", "sku", "store_id", "quantity",
                                "unit_price_cents", "total_cents", "status", "created_at",
                                "updated_at"],
                     [[o["order_id"], o["user_id"], o["sku"], o["store_id"], o["quantity"],
                       o["unit_price_cents"], o["unit_price_cents"] * o["quantity"],
                       o["status"], o["created_at"], o["created_at"]] for o in data["orders"]]),
             "COMMIT;"]
    return "\n".join(parts) + "\n"


def render_bug_tracker_seed() -> str:
    data = json.loads((DATA_DIR / "bug_tickets.json").read_text())
    parts = ["-- GENERATED by scripts/seed_demo_data.py from data/demo/bug_tickets.json.",
             "-- Fictional demo data. Do not edit by hand.", "BEGIN;",
             _insert("tickets", ["id", "title", "description", "status", "priority",
                                 "component", "reporter", "assignee", "created_at",
                                 "updated_at"],
                     [[t["id"], t["title"], t["description"], t["status"], t["priority"],
                       t["component"], t["reporter"], t["assignee"], t["created_at"],
                       t["created_at"]] for t in data["tickets"]]),
             _insert("comments", ["ticket_id", "author", "body", "created_at"],
                     [[c["ticket_id"], c["author"], c["body"], c["created_at"]]
                      for c in data["comments"]]),
             "SELECT setval('tickets_id_seq', (SELECT MAX(id) FROM tickets));",
             "COMMIT;"]
    return "\n".join(parts) + "\n"


SEED_FILES = {
    POSTGRES_DIR / "ecommerce_seed.sql": render_ecommerce_seed,
    POSTGRES_DIR / "bug_tracker_seed.sql": render_bug_tracker_seed,
}


def write_postgres_seeds() -> list[Path]:
    POSTGRES_DIR.mkdir(parents=True, exist_ok=True)
    for path, render in SEED_FILES.items():
        path.write_text(render())
    return list(SEED_FILES)


def reset_local_databases() -> dict[str, Path]:
    from agents.bug_assistant.mcp_server.store import TicketStore
    from agents.bug_assistant.mcp_server.store import load_seed as load_tickets
    from agents.ecommerce.mcp_server.store import CommerceStore
    from agents.ecommerce.mcp_server.store import load_seed as load_shop

    shop = CommerceStore(state_dir() / "ecommerce.sqlite")
    shop.initialize(load_shop(DATA_DIR / "ecommerce.json"), reset=True)
    bugs = TicketStore(state_dir() / "bug_tracker.sqlite")
    bugs.initialize(load_tickets(DATA_DIR / "bug_tickets.json"), reset=True)
    return {"ecommerce": shop.db_path, "bug_tracker": bugs.db_path}
